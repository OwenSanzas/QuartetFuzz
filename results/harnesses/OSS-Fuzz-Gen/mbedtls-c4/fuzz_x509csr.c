typedef struct {
    const uint8_t *data;
    size_t size;
} ext_cb_ctx_t;

static int dummy_ext_cb(void *p_ctx, mbedtls_x509_csr const *csr,
                         mbedtls_x509_buf const *oid, int critical,
                         const unsigned char *p, const unsigned char *end)
{
    (void) csr; (void) oid; (void) p; (void) end;
    const ext_cb_ctx_t *ctx = (const ext_cb_ctx_t *) p_ctx;
    if (ctx != NULL && ctx->size > 0) {

        if (critical && (ctx->data[0] & 1)) {
            return -1;
        }
    }
    return 0;
}

static void try_pem_envelope(const char *header, const char *footer,
                              const unsigned char *data, size_t size,
                              int encrypted_style)
{
    size_t b64_len = 0;

    mbedtls_base64_encode(NULL, 0, &b64_len, data, size);
    if (b64_len == 0) {
        b64_len = 1;
    }
    unsigned char *b64 = (unsigned char *) malloc(b64_len + 1);
    if (!b64) {
        return;
    }
    size_t olen = 0;
    int enc_ret = mbedtls_base64_encode(b64, b64_len, &olen, data, size);
    if (enc_ret != 0) {
        free(b64);
        return;
    }
    b64[olen] = '\0';

    const char *enc_hdr = encrypted_style ?
        "Proc-Type: 4,ENCRYPTED\nDEK-Info: DES-EDE3-CBC,0102030405060708\n\n" : "";

    size_t total = strlen(header) + 1   + strlen(enc_hdr) +
                   olen + 1   + strlen(footer) + 2;
    unsigned char *pem = (unsigned char *) malloc(total);
    if (!pem) {
        free(b64);
        return;
    }
    int n = snprintf((char *) pem, total, "%s\n%s%s\n%s\n",
                      header, enc_hdr, (char *) b64, footer);
    if (n > 0) {
        mbedtls_x509_csr csr;
        mbedtls_x509_csr_init(&csr);

        (void) mbedtls_x509_csr_parse(&csr, pem, (size_t) n + 1);
        mbedtls_x509_csr_free(&csr);
    }
    free(pem);
    free(b64);
}

