static void splice_region(unsigned char *buf, size_t off, size_t len,
                           const uint8_t *data, size_t size)
{
    if (size == 0) {
        return;
    }
    for (size_t i = 0; i < len; i++) {
        buf[off + i] = data[i % size];
    }
}

static void fuzz_via_template(const unsigned char *tmpl, size_t tmpl_len,
                               size_t cn_off, size_t cn_len,
                               size_t key_off, size_t key_len,
                               size_t sig_off, size_t sig_len,
                               int splice_key,
                               const uint8_t *data, size_t size)
{
    if (size == 0 || tmpl_len == 0) {
        return;
    }
    unsigned char *mut = (unsigned char *) malloc(tmpl_len);
    if (!mut) {
        return;
    }
    memcpy(mut, tmpl, tmpl_len);

    splice_region(mut, cn_off, cn_len, data, size);
    if (splice_key) {
        splice_region(mut, key_off, key_len, data, size);
    }
    splice_region(mut, sig_off, sig_len, data, size);

    mbedtls_x509_csr csr;

    mbedtls_x509_csr_init(&csr);
    (void) mbedtls_x509_csr_parse(&csr, mut, tmpl_len);
    mbedtls_x509_csr_free(&csr);

    ext_cb_ctx_t ctx = { data, size };
    mbedtls_x509_csr_init(&csr);
    (void) mbedtls_x509_csr_parse_der_with_ext_cb(&csr, mut, tmpl_len,
                                                   dummy_ext_cb, &ctx);
    mbedtls_x509_csr_free(&csr);

    free(mut);
}

