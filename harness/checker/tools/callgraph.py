"""The three call-graph tools of the +Static ablation: get_callers, get_callees,
find_path, over :class:`harness.checker.callgraph.CallGraph`.

Mounted in place of ``static_analysis`` when ``ctx.callgraph`` is loaded (see
:func:`harness.checker.tools.register_all`).  Results are text.  A function
name may be ambiguous (C++ overloads, same-named statics in several files):
up to ``_MAX_DEFS`` definitions are answered one by one, more return the
candidates so the agent can pass ``file``.
"""

from __future__ import annotations

from mcp.server.fastmcp import FastMCP

from harness.checker.callgraph import CallGraph, Func
from harness.checker.tools.context import CheckerContext

_MAX_LIST_ITEMS = 50
_MAX_DEFS = 5
_MAX_CANDIDATES = 30


def register(mcp: FastMCP, ctx: CheckerContext) -> None:
    g: CallGraph = ctx.callgraph
    root = ctx.project_path

    def where(f: Func) -> str:
        tag = "" if (root / f.file).exists() else "   [generated by the build, not in the source tree]"
        return f"{f.name}   ({f.loc()}){tag}"

    def not_found(name: str, file: str) -> str:
        msg = f"'{name}'{f' in {file}' if file else ''} is not a function in the call graph."
        sim = g.similar(name)
        if sim:
            msg += "  Similar names: " + ", ".join(sim)
        return msg + "  (Macros, libc and code outside the project are not in the graph; use Grep.)"

    def candidates(name: str, defs: list[Func]) -> str:
        lines = [f"{len(defs)} definitions named '{name}'; pass `file` (a path suffix, "
                 f"optionally ':line') to pick one:"]
        lines += [f"  {f.loc()}" for f in defs[:_MAX_CANDIDATES]]
        if len(defs) > _MAX_CANDIDATES:
            lines.append(f"  ... ({len(defs) - _MAX_CANDIDATES} more)")
        return "\n".join(lines)

    def neighbours(name: str, file: str, edges: dict[int, list[int]], what: str) -> str:
        defs = g.resolve(name, file)
        if not defs:
            return not_found(name, file)
        if len(defs) > _MAX_DEFS:
            return candidates(name, defs)
        out = []
        for d in defs:
            ns = sorted((g.funcs[i] for i in edges.get(d.id, ())), key=lambda f: (f.name, f.file, f.line))
            out.append(f"{len(ns)} {what} of {d.name} ({d.loc()}):")
            out += [f"  {where(f)}" for f in ns[:_MAX_LIST_ITEMS]]
            if len(ns) > _MAX_LIST_ITEMS:
                out.append(f"  ... ({len(ns) - _MAX_LIST_ITEMS} more)")
        out.append("(Static graph: calls through function pointers or virtual dispatch may be missing.)")
        return "\n".join(out)

    @mcp.tool()
    def get_callers(name: str, file: str = ""):
        """List the functions that call `name` in the project's static call graph.

        Args:
            name: Function name; `Class::method` or a bare name.
            file: Optional path suffix of the definition (e.g. `src/parse.c` or
                `src/parse.c:120`) when the name has several definitions.
        """
        return neighbours(name, file, g.callers, "callers")

    @mcp.tool()
    def get_callees(name: str, file: str = ""):
        """List the functions that `name` calls in the project's static call graph.

        Args:
            name: Function name; `Class::method` or a bare name.
            file: Optional path suffix of the definition (e.g. `src/parse.c` or
                `src/parse.c:120`) when the name has several definitions.
        """
        return neighbours(name, file, g.callees, "callees")

    @mcp.tool()
    def find_path(from_function: str, to_function: str, from_file: str = "", to_file: str = ""):
        """Shortest call chain from `from_function` to `to_function` in the
        project's static call graph, one function per line with its location.

        Args:
            from_function: Where the chain starts (e.g. the API your harness calls).
            to_function: Where it must arrive (e.g. the target function).
            from_file: Optional path suffix narrowing `from_function`'s definitions.
            to_file: Optional path suffix narrowing `to_function`'s definitions.
        """
        src = g.resolve(from_function, from_file)
        dst = g.resolve(to_function, to_file)
        if not src:
            return not_found(from_function, from_file)
        if not dst:
            return not_found(to_function, to_file)
        chain = g.shortest_path(src, dst)
        if chain is None:
            return (f"No call chain from '{from_function}' to '{to_function}' within 30 calls in "
                    f"the static graph.  Calls through function pointers, callbacks or virtual "
                    f"dispatch are often missing: read the code between them.")
        lines = [f"Call chain ({len(chain) - 1} calls):"]
        lines += [f"  {'-> ' if i else '   '}{where(f)}" for i, f in enumerate(chain)]
        return "\n".join(lines)
